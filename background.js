// background.js - Service Worker for Maeve (Powered exclusively by Groq)

const HARDCODED_SYSTEM_PROMPT =
  "You are Maeve, a concise AI assistant in a floating HUD. Answer directly and informatively in 2 to 4 short sentences. Do not use conversational filler, greetings, preamble, or pleasantries. Get straight to the point.";

// Cache parsed .env
let envCache = null;

// Parse .env file packaged with the extension
async function getEnvConfig() {
  if (envCache) return envCache;

  const config = {
    GROQ_API_KEY: "",
    GROQ_MODEL: "openai/gpt-oss-120b"
  };

  try {
    const url = chrome.runtime.getURL(".env");
    const res = await fetch(url);
    if (res.ok) {
      const text = await res.text();
      const lines = text.split(/\r?\n/);
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) continue;
        const equalIdx = trimmed.indexOf("=");
        if (equalIdx > 0) {
          const key = trimmed.slice(0, equalIdx).trim();
          let value = trimmed.slice(equalIdx + 1).trim();
          if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
            value = value.slice(1, -1);
          }
          config[key] = value;
        }
      }
    }
  } catch (err) {
    console.warn("Could not read .env file:", err);
  }

  envCache = config;
  return config;
}

chrome.runtime.onInstalled?.addListener(() => { envCache = null; });

// Listen for keyboard command (Alt+J / Cmd+Shift+K)
chrome.commands.onCommand.addListener(async (command) => {
  if (command === "toggle-ai-bar") {
    const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (tab && tab.id) {
      chrome.tabs.sendMessage(tab.id, { action: "TOGGLE_FLOATING_BAR" }).catch(() => {});
    }
  }
});

// Message listener
chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
  if (request.action === "QUERY_AI") {
    handleMaeveQuery(request.prompt)
      .then((reply) => sendResponse({ success: true, text: reply }))
      .catch((err) => sendResponse({ success: false, error: err.message || String(err) }));
    return true;
  }

  if (request.action === "TOGGLE_ACTIVE_TAB") {
    chrome.tabs.query({ active: true, currentWindow: true }).then(([tab]) => {
      if (tab && tab.id) {
        chrome.tabs.sendMessage(tab.id, { action: "TOGGLE_FLOATING_BAR" }).catch(() => {});
      }
    });
    sendResponse({ success: true });
    return true;
  }

  if (request.action === "GET_STATUS") {
    getEnvConfig().then((env) => {
      sendResponse({
        hasGroq: Boolean(env.GROQ_API_KEY?.trim()),
        model: env.GROQ_MODEL || "openai/gpt-oss-120b"
      });
    });
    return true;
  }
});

async function handleMaeveQuery(prompt) {
  const env = await getEnvConfig();
  const apiKey = env.GROQ_API_KEY?.trim();

  if (!apiKey) {
    throw new Error("Missing GROQ_API_KEY in .env file. Open .env, paste your Groq key, and reload the extension.");
  }

  const model = env.GROQ_MODEL?.trim() || "openai/gpt-oss-120b";
  const url = "https://api.groq.com/openai/v1/chat/completions";

  const res = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${apiKey}`
    },
    body: JSON.stringify({
      model: model,
      messages: [
        { role: "system", content: HARDCODED_SYSTEM_PROMPT },
        { role: "user", content: prompt }
      ],
      max_tokens: 160,
      temperature: 0.6
    })
  });

  const data = await res.json();
  if (!res.ok) {
    const errorMsg = data.error?.message || `Groq API returned status ${res.status}`;
    throw new Error(errorMsg);
  }

  const text = data.choices?.[0]?.message?.content;
  if (!text) {
    throw new Error("No response generated by Groq.");
  }
  return text.trim();
}
